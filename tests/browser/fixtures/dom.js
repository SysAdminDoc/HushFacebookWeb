import { createPostTracker } from '../../../src/core/dom/posts.js';
import { createSettings } from '../../../src/core/settings.js';
import { createMemoryStorage } from '../../../src/core/storage.js';
import { mountFeatureStyles } from '../../../src/core/style.js';
import shareSheet, { createShareSheetMarker } from '../../../src/features/links/share-sheet.js';
import { check, quietLog, until } from './helpers.js';

export async function stagedShare() {
  const settings = createSettings({ storage: createMemoryStorage(), features: [shareSheet], migrations: [] });
  settings.set('shareSheet', true);
  mountFeatureStyles({ features: [shareSheet], settings, doc: document });
  const marker = createShareSheetMarker({ doc: document, enabled: () => settings.enabled('shareSheet') });
  marker.start();
  const dialog = document.createElement('section');
  dialog.setAttribute('role', 'dialog');
  dialog.innerHTML = '<h2>Share</h2><div role="list"><div role="listitem"><a>Loading target</a></div><div role="listitem"><a>Loading target</a></div><div role="listitem"><button role="button">Loading control</button></div></div>';
  document.body.append(dialog);
  const [target, second, copy] = dialog.querySelectorAll('[role="listitem"]');
  const link = target.querySelector('a');
  await until(() => dialog.isConnected, 'Share fixture did not mount');
  check(!target.hasAttribute('data-hfw-share'), 'An unfinished share target was hidden');
  link.href = 'https://wa.me/?text=fixture';
  link.textContent = 'WhatsApp';
  second.querySelector('a').href = 'https://x.com/intent/post?text=fixture';
  second.querySelector('a').textContent = 'X';
  copy.querySelector('button').textContent = 'Copy link';
  await until(() => target.getAttribute('data-hfw-share') === 'whatsapp', 'A late share target was missed');
  check(!target.checkVisibility() && copy.checkVisibility(), 'Share filtering hid the wrong control');
  link.href = '/ordinary';
  link.textContent = 'Copy link';
  await until(() => !target.hasAttribute('data-hfw-share'), 'A reused row kept its stale share mark');
  check(target.checkVisibility(), 'A reused row remained hidden');
  dialog.querySelector('h2').textContent = 'Compartir';
  link.href = 'https://x.com/intent/post?text=fixture';
  link.textContent = 'Enviar';
  second.querySelector('a').href = 'https://wa.me/?text=fixture';
  second.querySelector('a').textContent = 'Enviar';
  await until(() => target.getAttribute('data-hfw-share') === 'x' && second.getAttribute('data-hfw-share') === 'whatsapp', 'Localized share intents were missed');
  check(copy.checkVisibility() && !target.checkVisibility() && !second.checkVisibility(), 'Localized target visibility is wrong');
  const unrelated = document.createElement('section');
  unrelated.setAttribute('role', 'dialog');
  unrelated.innerHTML = '<h2>Profiles</h2><div role="list"><div role="listitem"><a href="https://x.com/fixture">Profile one</a></div><div role="listitem"><a href="https://whatsapp.com/fixture">Profile two</a></div></div>';
  document.body.append(unrelated);
  marker.sync();
  check(!unrelated.querySelector('[data-hfw-share]'), 'Ordinary social profiles were treated as share targets');
  marker.stop();
  return { hidden: 2, copyVisible: true, ordinaryProfilesMarked: false };
}

export async function recycledPosts() {
  const errors = [];
  const feed = document.createElement('main');
  feed.innerHTML = '<div class="slot"><article role="article"><a href="/fixture/posts/pfbid0FixtureInner">Inner post</a></article></div>';
  document.body.append(feed);
  const tracker = createPostTracker({ doc: document, log: quietLog(errors) });
  const events = [];
  tracker.on('post/add', (post) => events.push(['add', post.id]));
  tracker.on('post/remove', (post) => events.push(['remove', post.id]));
  const ids = () => tracker.current().map((post) => post.id).join(',');
  check(ids() === 'pfbid0FixtureInner', 'The initial article was not tracked');
  const slot = feed.querySelector('.slot');
  const outer = document.createElement('div');
  outer.setAttribute('aria-posinset', '1');
  outer.innerHTML = '<a href="/fixture/posts/pfbid0FixtureOuter">Outer post</a>';
  slot.replaceWith(outer);
  outer.append(slot);
  await until(() => ids() === 'pfbid0FixtureOuter', 'Wrapping did not demote the nested article');
  outer.removeAttribute('aria-posinset');
  await until(() => ids() === 'pfbid0FixtureInner', 'Removing the wrapper role did not promote its article');
  outer.setAttribute('aria-posinset', '1');
  await until(() => ids() === 'pfbid0FixtureOuter', 'A recycled wrapper was not promoted again');
  outer.setAttribute('role', 'listitem');
  await until(() => ids() === 'pfbid0FixtureInner', 'A recycled widget stayed in the post registry');
  slot.querySelector('a').href = '/fixture/posts/pfbid0FixtureReused';
  await until(() => ids() === 'pfbid0FixtureReused', 'A reused post kept its old identity');
  check(events.at(-2)?.join(',') === 'remove,pfbid0FixtureInner' && events.at(-1)?.join(',') === 'add,pfbid0FixtureReused', 'A reused story did not remove then add');
  check(errors.length === 0, 'Post tracking logged an error');
  tracker.stop();
  return { events };
}
